{{-- ================= BAB 4 ================= --}}
<div class="manual-section" id="bab4">
    <h2><i class="bi bi-droplet-half"></i> Bab 4 — Audit Mandiri Cuci Tangan</h2>
    <div class="manual-card">
        <p>Lembar observasi kepatuhan cuci tangan <b>5 Momen WHO</b> — maksimal <b>24 peluang</b> per lembar. Nama Anda otomatis menjadi <b>Observer</b> dan unit terkunci pada unit Anda.</p>
        <ol class="manual-steps">
            <li><b>Buka menu "Audit Cuci Tangan"</b>Di sidebar, pilih <b>Audit PPI → Audit Cuci Tangan</b> (atau tombol <b>Audit</b> di menu bawah layar HP).</li>
            <li><b>Isi Identitas</b>Tanggal, shift, nama petugas yang diobservasi (opsional), dan profesinya.</li>
            <li><b>Amati tiap peluang (1–24)</b>Untuk setiap peluang cuci tangan yang diamati:
                <ul class="mt-1 mb-0">
                    <li>Centang <b>Momen</b> yang terjadi: M1 sebelum kontak pasien · M2 sebelum prosedur aseptik · M3 setelah risiko cairan tubuh · M4 setelah kontak pasien · M5 setelah kontak lingkungan.</li>
                    <li>Centang <b>Tindakan</b>: <span class="text-success fw-semibold">HR</span> / <span class="text-success fw-semibold">HW</span> / <span class="text-success fw-semibold">Set. lepas sarung tangan</span> = <b>PATUH</b> · <span class="text-danger fw-semibold">Tidak melakukan</span> = <b>TIDAK PATUH</b>.</li>
                </ul>
            </li>
            <li><b>Simpan</b>Klik <b>Simpan &amp; Hitung Kepatuhan</b> — minimal 1 observasi terisi; momen &amp; tindakan wajib berpasangan.</li>
        </ol>
    </div>
</div>

{{-- ================= BAB 5 ================= --}}
<div class="manual-section" id="bab5">
    <h2><i class="bi bi-person-badge"></i> Bab 5 — Audit Mandiri APD</h2>
    <div class="manual-card">
        <ol class="manual-steps">
            <li><b>Buka menu "Audit APD"</b>Di sidebar, pilih <b>Audit PPI → Audit APD</b>. Anda tercatat sebagai auditor dan unit terkunci pada unit Anda.</li>
            <li><b>Isi Data Awal</b>Tanggal, shift, nama petugas, profesi, dan <b>Pilih Tindakan yang Diobservasi</b> (wajib).</li>
            <li><b>Nilai 6 Jenis APD</b>Untuk tindakan tersebut, nilai penggunaan: <b>Sarung Tangan, Masker, Goggle, Apron, Tutup Kepala, Sepatu Boot</b> — <b>Ya</b> bila sesuai, <b>Tidak</b> bila tidak digunakan, <b>N/A</b> bila tidak relevan.</li>
            <li><b>Isi temuan bila ada "Tidak"</b>Setiap jawaban <b>Tidak</b> membuka form temuan: uraian, lokasi, tingkat, foto bukti (maks 5MB), dan rekomendasi. Isi selengkap mungkin.</li>
            <li><b>Simpan</b>Skor kepatuhan &amp; predikat dihitung otomatis (Sangat Baik ≥90 · Baik ≥80 · Cukup ≥70 · &lt;70 Perlu Perbaikan).</li>
        </ol>
    </div>
</div>

{{-- ================= BAB 6 ================= --}}
<div class="manual-section" id="bab6">
    <h2><i class="bi bi-journal-check"></i> Bab 6 — Riwayat Audit Unit</h2>
    <div class="manual-card">
        <p>Menu <b>Audit PPI → Riwayat Audit</b> menampilkan seluruh audit pada unit Anda — baik hasil audit mandiri maupun audit oleh tim PPI. Anda dapat mencari (nomor/nama petugas), filter kategori/tanggal/shift/predikat, membuka detail, dan mengunduh <b>PDF</b> lembar audit.</p>
    </div>
</div>

{{-- ================= BAB 7 ================= --}}
<div class="manual-section" id="bab7">
    <h2><i class="bi bi-exclamation-triangle-fill"></i> Bab 7 — Melihat Temuan Unit</h2>
    <div class="manual-card">
        <p>Menu <b>Surveilans → Monitoring Temuan</b> menampilkan temuan yang diterima unit Anda:</p>
        <ul>
            <li><b>Status</b> — <span class="badge bg-danger">OPEN</span> belum ditindaklanjuti · <span class="badge bg-warning text-dark">PROGRESS</span> sedang diproses · <span class="badge bg-success">CLOSED</span> selesai.</li>
            <li><b>Tingkat</b> — MINOR / MAYOR / KRITIS; dahulukan temuan KRITIS.</li>
            <li><b>Jatuh tempo</b> — batas waktu tindak lanjut (umumnya 7 hari sejak temuan dibuat). Baris merah = TERLAMBAT.</li>
        </ul>
        <p>Klik nomor temuan (cth. <code>TMN-2026-0001</code>) untuk melihat uraian lengkap, foto, rekomendasi, dan riwayat tindak lanjut.</p>
    </div>
</div>

{{-- ================= BAB 8 ================= --}}
<div class="manual-section" id="bab8">
    <h2><i class="bi bi-arrow-repeat"></i> Bab 8 — Mengirim Tindak Lanjut Temuan</h2>
    <div class="manual-card">
        <p>Ini adalah tugas terpenting unit. Langkah-langkah:</p>
        <ol class="manual-steps">
            <li><b>Buka menu Tindak Lanjut</b>Menu <b>Surveilans → Tindak Lanjut</b> menampilkan temuan unit yang memerlukan tindakan (diurutkan paling urgent). Klik tombol <b>Tindak Lanjut</b>.</li>
            <li><b>Lakukan perbaikan nyata</b>Perbaiki masalah sesuai uraian temuan &amp; rekomendasi auditor di lapangan.</li>
            <li><b>Isi form tindak lanjut</b>Tulis <b>Uraian Tindakan</b> (wajib), <b>Tanggal perbaikan</b> (wajib), dan unggah <b>Foto bukti</b> perbaikan (disarankan, maks 5MB — bisa langsung dari kamera HP).</li>
            <li><b>Kirim</b>Status temuan berubah menjadi <span class="badge bg-warning text-dark">PROGRESS</span> dan menunggu verifikasi auditor/admin.</li>
            <li><b>Tunggu hasil verifikasi</b>
                <ul class="mt-1 mb-0">
                    <li><b>Disetujui</b> → temuan <span class="badge bg-success">CLOSED</span> (selesai 🎉).</li>
                    <li><b>Revisi</b> → temuan kembali <span class="badge bg-danger">OPEN</span>; baca catatan auditor lalu kirim tindak lanjut ulang.</li>
                </ul>
            </li>
        </ol>
        <div class="manual-warn"><i class="bi bi-exclamation-triangle-fill text-warning"></i>
            <div>Sampaikan tindak lanjut <b>sebelum jatuh tempo</b>. Selama satu tindak lanjut masih menunggu verifikasi, pengiriman tindak lanjut berikutnya untuk temuan yang sama ditunda.</div>
        </div>
    </div>
</div>

{{-- ================= BAB 9 ================= --}}
<div class="manual-section" id="bab9">
    <h2><i class="bi bi-eyedropper"></i> Bab 9 — Monitoring Limbah Benda Tajam</h2>
    <div class="manual-card">
        <p>Menu <b>Surveilans → Monitoring Limbah Tajam</b> digunakan mengisi lembar monitoring penanganan limbah benda tajam di unit Anda:</p>
        <ol class="manual-steps">
            <li><b>Isi identitas</b>Unit, petugas, tanggal, dan shift.</li>
            <li><b>Jawab 8 pernyataan Ya/Tidak</b>Meliputi: tidak menutup kembali jarum (no recapping), tidak memberi benda tajam langsung ke orang lain, penggunaan container, pembuangan ke safety box, safety box ditutup saat terisi 3/4, tidak membengkokkan/mematahkan jarum, jarum tidak dilepas manual, dan ketersediaan safety box di tiap titik pelayanan.</li>
            <li><b>Simpan</b>Persentase ketercapaian dihitung otomatis.</li>
            <li><b>Riwayat &amp; cetak</b>Semua lembar tersimpan di menu riwayat dan dapat dicetak/unduh PDF.</li>
        </ol>
    </div>
</div>

