{{-- ================= BAB 1 ================= --}}
<div class="manual-section" id="bab1">
    <h2><i class="bi bi-hospital-fill"></i> Bab 1 — Pendahuluan &amp; Peran Unit</h2>
    <div class="manual-card">
        <p>Akun Anda terhubung dengan satu <b>Unit / Ruangan</b>. Sebagai pengguna <b>Unit / Petugas</b>, tugas utama Anda:</p>
        <ul>
            <li>🧼 Melaksanakan <b>Audit Mandiri Cuci Tangan</b> dan <b>Audit Mandiri APD</b> untuk unit Anda sendiri.</li>
            <li>👀 Memantau <b>temuan</b> yang diterima unit dari hasil audit PPI.</li>
            <li>📝 Mengirimkan <b>tindak lanjut</b> atas setiap temuan <b>sebelum jatuh tempo</b>, disertai bukti perbaikan.</li>
            <li>💉 Mengisi <b>Lembar Monitoring Penanganan Limbah Benda Tajam</b>.</li>
        </ul>
        <div class="manual-note"><i class="bi bi-lightbulb-fill text-brand"></i>
            <div>Semua data yang Anda lihat otomatis <b>terbatas pada unit Anda sendiri</b> — temuan, riwayat audit, dan laporan unit lain tidak akan tampil pada akun Anda.</div>
        </div>
        <div class="manual-note"><i class="bi bi-stars text-brand"></i>
            <div><b>BARU:</b> Kini unit juga dapat melaksanakan sendiri <b>Audit Cuci Tangan</b> dan <b>Audit APD</b> (audit mandiri) langsung dari menu Audit PPI — tanpa menunggu auditor datang.</div>
        </div>
    </div>
</div>

{{-- ================= BAB 2 ================= --}}
<div class="manual-section" id="bab2">
    <h2><i class="bi bi-box-arrow-in-right"></i> Bab 2 — Login &amp; Logout</h2>
    <div class="manual-card">
        <ol class="manual-steps">
            <li><b>Buka aplikasi</b>Buka alamat aplikasi pada browser (HP/laptop), lalu klik <b>Login</b>.</li>
            <li><b>Isi Email &amp; Kata Sandi</b>Gunakan akun unit yang diberikan Admin PPI.</li>
            <li><b>Isi Kode Captcha</b>Ketik kode pada gambar captcha, lalu klik <b>Masuk</b>.</li>
            <li><b>Logout</b>Klik avatar kanan atas → <b>Keluar</b> bila memakai perangkat bersama.</li>
        </ol>
        <div class="manual-warn"><i class="bi bi-exclamation-triangle-fill text-warning"></i>
            <div>Lupa kata sandi? Hubungi <b>Super Admin / Admin PPI</b>. Jangan meminjamkan akun Anda ke unit lain.</div>
        </div>
    </div>
</div>

